function formatItems(items) {
  return items
    .map((item) =>
      [item.name, item.dosage, item.frequency, item.reaction, item.severity]
        .filter(Boolean)
        .join(" — "),
    )
    .filter(Boolean)
    .join(", ");
}

function demoCopilotAnswer(question, language) {
  const text = copilotText[language] || copilotText.en;
  const query = question.toLowerCase();
  const profile = readStore(PROFILE_KEY, initialProfile);
  const records = readStore(RECORDS_KEY, []);
  let answer = text.unknown;

  if (/medicat|medicine|medicin|drug|दवा|औषध|દવા|மருந்த|ওষুধ/i.test(query)) {
    const medications = (profile.medications || []).filter(
      (item) => item.active !== false,
    );
    answer = medications.length
      ? `${text.medications}: ${formatItems(medications)}.`
      : text.noMedications;
  } else if (/allerg|अॅलर्जी|एलर्जी|ਐਲਰਜ|એલર્જ|ஒவ்வாம|অ্যালার্জ/i.test(query)) {
    answer = profile.allergies?.length
      ? `${text.allergies}: ${formatItems(profile.allergies)}.`
      : text.noAllergies;
  } else if (/condition|diagnos|medical histor|health condition|बीमारी|स्थिति|स्थिती|બીમારી|நிலை|রোগ|অবস্থা/i.test(query)) {
    const conditions = profile.medicalConditions || [];
    answer = conditions.length
      ? `${text.conditions}: ${formatItems(conditions)}.`
      : text.noConditions;
  } else if (/blood|रक्तगट|ब्लड ग्रुप|રક્ત|இரத்த வகை|রক্তের গ্রুপ/i.test(query)) {
    answer = profile.bloodGroup
      ? `${text.bloodGroup}: ${profile.bloodGroup}.`
      : text.noBloodGroup;
  } else if (/height|लंबाई|उंची|ઊંચાઈ|உயரம்|উচ্চতা/i.test(query)) {
    answer = profile.height?.value
      ? `${text.height}: ${profile.height.value} ${profile.height.unit || "cm"}.`
      : text.noHeight;
  } else if (/weight|वज़न|वजन|વજન|எடை|ওজন/i.test(query)) {
    answer = profile.weight?.value
      ? `${text.weight}: ${profile.weight.value} ${profile.weight.unit || "kg"}.`
      : text.noWeight;
  } else if (/record|report|records|रिकॉर्ड|नोंद|નોંધ|பதிவ|রেকর্ড/i.test(query)) {
    answer = records.length
      ? `${text.records(records.length)} ${records.slice(0, 5).map((record) => record.title).filter(Boolean).join(", ")}`
      : text.noRecords;
  }

  return `${text.demo}\n\n${answer}`;
}

export async function mockApiAdapter(config) {
  const requestUrl = config.url || "";
  const baseUrl = config.baseURL || "";
  const absoluteRequestUrl = /^([a-z][a-z\d+\-.]*:)?\/\//i.test(requestUrl);
  const url = absoluteRequestUrl
    ? new URL(requestUrl)
    : new URL(
        `${baseUrl.replace(/\/+$/, "")}/${requestUrl.replace(/^\/+/, "")}`,
        window.location.origin,
      );
  const path = url.pathname.replace(/^\/api(?=\/|$)/, "") || "/";
  const method = (config.method || "get").toUpperCase();
  const body = bodyOf(config);

  if (method === "GET" && path === "/profile") {
    return response(config, {
      user: readStore(USER_KEY, initialUser),
      profile: readStore(PROFILE_KEY, initialProfile),
    });
  }

  if (method === "PUT" && path === "/profile/user") {
    const user = writeStore(USER_KEY, {
      ...readStore(USER_KEY, initialUser),
      ...body,
    });
    return response(config, user);
  }

  if (method === "PUT" && path === "/profile") {
    const profile = writeStore(PROFILE_KEY, {
      ...readStore(PROFILE_KEY, initialProfile),
      ...body,
      userId: "demo-user",
    });
    return response(config, profile);
  }

  if (method === "GET" && path === "/records") {
    return response(config, readStore(RECORDS_KEY, []));
  }

  if (method === "POST" && path === "/records") {
    const records = readStore(RECORDS_KEY, []);
    const record = {
      ...body,
      _id: `demo-record-${Date.now()}`,
      userId: "demo-user",
      createdAt: new Date().toISOString(),
    };
    writeStore(RECORDS_KEY, [record, ...records]);
    return response(config, record, 201);
  }

  const recordMatch = path.match(/^\/records\/([^/]+)$/);
  if (method === "DELETE" && recordMatch) {
    const records = readStore(RECORDS_KEY, []).filter(
      (record) => record._id !== recordMatch[1],
    );
    writeStore(RECORDS_KEY, records);
    return response(config, { message: "Record deleted" });
  }

  if (method === "GET" && path === "/doctors") {
    const params = config.params || {};
    const search = String(params.search || "").trim().toLowerCase();
    const specialty = String(params.specialty || "").trim().toLowerCase();
    const doctors = demoDoctors.filter((doctor) => {
      const matchesSearch =
        !search ||
        [doctor.name, doctor.clinicName, doctor.address, doctor.city, doctor.specialty]
          .some((value) => value.toLowerCase().includes(search));
      const matchesSpecialty =
        !specialty || doctor.specialty.toLowerCase().includes(specialty);
      return matchesSearch && matchesSpecialty;
    });
    return response(config, { doctors });
  }

  if (method === "POST" && path === "/share/create") {
    const links = readStore(LINKS_KEY, []);
    const token = `demo-share-${Date.now()}`;
    const expiresAt = new Date(Date.now() + 60 * 60 * 1000).toISOString();
    writeStore(LINKS_KEY, [
      { _id: token, token, expiresAt, revoked: false, accessCount: 0 },
      ...links,
    ]);
    return response(config, {
      url: `${window.location.origin}/doctor/${token}`,
      expiresAt,
    });
  }

  if (method === "GET" && path === "/share/my-links") {
    return response(config, readStore(LINKS_KEY, []));
  }

  const shareDeleteMatch = path.match(/^\/share\/([^/]+)$/);
  if (method === "DELETE" && shareDeleteMatch) {
    const links = readStore(LINKS_KEY, []).map((link) =>
      link._id === shareDeleteMatch[1] ? { ...link, revoked: true } : link,
    );
    writeStore(LINKS_KEY, links);
    return response(config, { message: "Share link revoked" });
  }

  const shareViewMatch = path.match(/^\/share\/view\/([^/]+)$/);
  if (method === "GET" && shareViewMatch) {
    const links = readStore(LINKS_KEY, []);
    const link = links.find(
      (item) =>
        item.token === shareViewMatch[1] &&
        !item.revoked &&
        new Date(item.expiresAt) > new Date(),
    );

    if (!link) {
      return fail(config, 404, "Link expired or invalid");
    }

    writeStore(
      LINKS_KEY,
      links.map((item) =>
        item._id === link._id
          ? { ...item, accessCount: item.accessCount + 1 }
          : item,
      ),
    );
    return response(config, {
      user: readStore(USER_KEY, initialUser),
      profile: readStore(PROFILE_KEY, initialProfile),
      records: readStore(RECORDS_KEY, []),
    });
  }

  if (method === "POST" && path === "/copilot") {
    return response(config, {
      answer: demoCopilotAnswer(
        String(body.question || ""),
        String(body.language || "en"),
      ),
      isSample: true,
    });
  }

  return fail(config, 404, "This endpoint is unavailable in demo mode.");
}
